# 4. 文字整理
# ============================================================

def norm_text(x):

    if pd.isna(x):
        return ''

    return unicodedata.normalize(
        'NFKC',
        str(x)
    ).strip()


# ============================================================
# 5. 芝・ダート
# ============================================================

def normalize_td(x):

    s = norm_text(x)

    if (
        'ダ' in s
        or s.upper() == 'D'
    ):
        return 'ダート'

    if (
        '芝' in s
        or s.upper() == 'T'
    ):
        return '芝'

    return 'その他'


# ============================================================
# 6. 着順
# ============================================================

def parse_finish(x):

    if pd.isna(x):
        return np.nan

    s = norm_text(x)

    m = re.match(
        r'^(\d+)',
        s
    )

    if not m:
        return np.nan

    return int(
        m.group(1)
    )


# ============================================================
# 7. クラス
