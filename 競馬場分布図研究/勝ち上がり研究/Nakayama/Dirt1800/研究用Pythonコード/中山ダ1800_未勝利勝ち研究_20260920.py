def rpc_group(distance, rpci):

    if (
        pd.isna(distance)
        or pd.isna(rpci)
    ):
        return np.nan

    try:

        distance = int(distance)
        rpci = float(rpci)

    except:

        return np.nan


    if distance not in RPCI_BOUNDS:
        return np.nan


    q20, q40, q60, q80 = (
        RPCI_BOUNDS[distance]
    )


    if rpci < q20:
        return 'Q1_かなりハイ'

    if rpci < q40:
        return 'Q2_ハイ'

    if rpci <= q60:
        return 'Q3_中間'

    if rpci <= q80:
        return 'Q4_スロー'

    return 'Q5_かなりスロー'


