def class_group(x):

    s = norm_text(x).upper()

    if '新馬' in s:
        return '新馬'

    if '未勝利' in s:
        return '未勝利'

    if (
        '1勝' in s
        or '500万' in s
    ):
        return '1勝'

    if (
        '2勝' in s
        or '1000万' in s
    ):
        return '2勝'

    if (
        '3勝' in s
        or '1600万' in s
    ):
        return '3勝'

    if (
        'OP' in s
        or 'オープン' in s
        or '(L)' in s
        or 'LISTED' in s
        or 'G1' in s
        or 'G2' in s
        or 'G3' in s
        or '重賞' in s
    ):
        return 'OP以上'

    return np.nan


