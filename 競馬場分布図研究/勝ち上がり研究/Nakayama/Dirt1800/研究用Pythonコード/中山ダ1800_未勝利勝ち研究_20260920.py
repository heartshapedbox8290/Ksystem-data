def make_finish_route(
    df,
    finish
):

    x = df[
        df['着順_num']
        == finish
    ].copy()


    if len(x) == 0:

        return pd.DataFrame()


    out = (

        x
        .groupby(
            [
                '入口_RPCI区分',
                '入口_ポジション',

                '競馬場',
                '距離_num',

                'RPCI区分',
                'ポジション'
            ],
            dropna=False
        )
        .agg(

            馬数=(
                '_horse_id',
                'nunique'
            ),

            回数=(
                '_horse_id',
                'size'
            )

        )
        .reset_index()
    )


    out = out.rename(
        columns={

            '競馬場':
            '1勝クラス競馬場',

            '距離_num':
            '1勝クラス距離',

            'RPCI区分':
            '1勝クラス_RPCI区分',

            'ポジション':
            '1勝クラス_ポジション'
        }
    )


    return (

        out
        .sort_values(
            [
                '馬数',
                '回数'
            ],
            ascending=[
                False,
                False
            ]
        )
        .reset_index(
            drop=True
        )
    )


