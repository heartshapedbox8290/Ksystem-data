def make_course_finish_table(df):

    rows = []

    for finish in [1, 2, 3]:

        x = df[
            df['着順_num'] == finish
        ].copy()

        g = (
            x
            .groupby(
                [
                    '入口_RPCI区分',
                    '入口_ポジション',
                    '競馬場',
                    '距離_num'
                ],
                dropna=False
            )
            .agg(
                馬数=(
                    '_horse_id',
                    'nunique'
                ),
                回数=(
                    '_horse_id',
                    'size'
                )
            )
            .reset_index()
        )

        g['着順区分'] = finish

        rows.append(g)


    all_finish = pd.concat(
        rows,
        ignore_index=True
    )


    # ========================================================
    # 1着・2着・3着を横持ち
    # ========================================================

    pivot_horse = (
        all_finish
        .pivot_table(
            index=[
                '入口_RPCI区分',
                '入口_ポジション',
                '競馬場',
                '距離_num'
            ],
            columns='着順区分',
            values='馬数',
            aggfunc='sum',
            fill_value=0
        )
        .reset_index()
    )


    # 列名変更

    pivot_horse = pivot_horse.rename(
        columns={
            1: '1着馬数',
            2: '2着馬数',
            3: '3着馬数'
        }
    )


    # 列が存在しない場合の保険

    for col in [
        '1着馬数',
        '2着馬数',
        '3着馬数'
    ]:

        if col not in pivot_horse.columns:
            pivot_horse[col] = 0


    # ========================================================
    # 馬券内参考値
    #
    # 注意：
    # 同じ馬が別レースで
    # 2着・3着している場合があるので
    # 単純なユニーク馬数ではない
    #
    # あくまで見やすさ用
    # ========================================================

    pivot_horse['1～3着合計'] = (

        pivot_horse['1着馬数']
        +
        pivot_horse['2着馬数']
        +
        pivot_horse['3着馬数']
    )


    # ========================================================
    # 並べ替え
    # ========================================================

    pivot_horse = (

        pivot_horse
        .sort_values(
            [
                '入口_RPCI区分',
                '入口_ポジション',
                '1着馬数',
                '1～3着合計'
            ],
            ascending=[
                True,
                True,
                False,
                False
            ]
        )
        .reset_index(
            drop=True
        )
    )


    return pivot_horse


