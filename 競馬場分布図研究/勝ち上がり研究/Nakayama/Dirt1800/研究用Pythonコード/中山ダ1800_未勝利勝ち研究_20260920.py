def corner_number(x):

    if pd.isna(x):
        return np.nan

    s = norm_text(x)

    m = re.search(
        r'\d+',
        s
    )

    if not m:
        return np.nan

    return int(
        m.group()
    )


# ============================================================
# 11. ポジション判定
#
# 基本＝4角
#
# 4角 前1/3 → 1/3
# 4角 中1/3 → 2/3
# 4角 後1/3 → 3/3
#
#
# 例外①
#
# 1角 前1/3
# ↓
# 4角で下がっていても
# ↓
# 1/3
#
#
# 例外②
#
# 1角 後1/3
# ↓
# 4角 前1/3
# ↓
# まくり
#
# ============================================================

def position_group(row):

    n = row['頭数_num']
    c1 = row['1角_num']
    c4 = row['4角_num']


    if (
        pd.isna(n)
        or n <= 0
        or pd.isna(c4)
    ):
        return np.nan


    n = float(n)

    c4_ratio = (
        c4 / n
    )


    # --------------------------------------------------------
    # まず4角で基本判定
    # --------------------------------------------------------

    if c4_ratio <= (1 / 3):

        base = '1/3'

    elif c4_ratio <= (2 / 3):

        base = '2/3'

    else:

        base = '3/3'


    # --------------------------------------------------------
    # 1角が無い、または取得できない場合
    # --------------------------------------------------------

    if pd.isna(c1):

        return base


    c1_ratio = (
        c1 / n
    )


    # --------------------------------------------------------
    # 最優先：まくり
    #
    # 1角 後1/3
    # ↓
    # 4角 前1/3
    # --------------------------------------------------------

    if (
        c1_ratio > (2 / 3)
        and
        c4_ratio <= (1 / 3)
    ):

        return 'まくり'


    # --------------------------------------------------------
    # 1角で前1/3以内
    #
    # 4角までに下がっても
    # 先行した馬として1/3
    # --------------------------------------------------------

    if c1_ratio <= (1 / 3):

        return '1/3'


    return base


